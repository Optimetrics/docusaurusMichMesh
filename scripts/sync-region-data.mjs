// Refreshes the Region Configurator's bundled copy of the region data from
// the Michigan regions RFC repo. Run with:
//
//   npm run sync:regions
//
// or, to test changes in a local checkout of the RFC repo before they merge:
//
//   npm run sync:regions -- --from ../MC-Regional-Infrastructure-Planning
//
// then commit src/components/RegionConfigurator/snapshot.json. The page
// already loads the latest data when it opens; the snapshot is only what it
// shows if GitHub can't be reached, so refresh it whenever you're nearby, not
// on a schedule. See src/components/RegionConfigurator/README.md.

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { RFC_REPO, RFC_REF, RFC_FILES, fetchRfcData, normalize } from '../src/components/RegionConfigurator/regionData.mjs';

const OUT = 'src/components/RegionConfigurator/snapshot.json';

const fromIndex = process.argv.indexOf('--from');
const fromDir = fromIndex > -1 ? process.argv[fromIndex + 1] : null;

let commit, raw;
if (fromDir) {
  commit = execFileSync('git', ['-C', fromDir, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
  const dirty = execFileSync('git', ['-C', fromDir, 'status', '--porcelain', 'data'], { encoding: 'utf8' }).trim();
  if (dirty) commit += ' (with uncommitted changes)';
  raw = Object.fromEntries(
    Object.entries(RFC_FILES).map(([key, path]) => [key, JSON.parse(readFileSync(join(fromDir, path), 'utf8'))]),
  );
} else {
  const res = await fetch(`https://api.github.com/repos/${RFC_REPO}/commits/${RFC_REF}`, {
    headers: { Accept: 'application/vnd.github.sha' },
  });
  if (!res.ok) throw new Error(`Couldn't look up ${RFC_REPO}@${RFC_REF}: HTTP ${res.status}`);
  commit = (await res.text()).trim();
  // Fetch at the exact commit so the snapshot matches what _source says.
  raw = await fetchRfcData({ ref: commit });
}
const data = normalize(raw); // throws if the files don't have the expected shape

const snapshot = {
  _source: {
    repo: RFC_REPO,
    commit,
    files: Object.values(RFC_FILES),
    note: 'Generated by scripts/sync-region-data.mjs. Edit the RFC repo, not this file.',
  },
  ...raw,
};
writeFileSync(OUT, JSON.stringify(snapshot, null, 2) + '\n');
console.log(
  `sync-region-data: wrote ${OUT} from ${RFC_REPO}@${commit.slice(0, 7)} ` +
    `(${Object.keys(data.counties).length} counties, ${data.locals.length} local regions in use, ` +
    `${Object.keys(data.places).length} places)`,
);
